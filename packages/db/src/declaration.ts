import type { Annotations, ResolvedColumn, ResolvedDatabase } from '~/schema';

export interface DeclarationOptions {
  /** One ambient declaration file containing a module for every database schema. */
  files: { declarations: string };
  /** Ambient module prefix. Defaults to odb for models and odb/kysely for Kysely. */
  prefix?: string;
}

export const valueDeclarations = [
  'export type JsonValue = null | boolean | number | string | JsonValue[] | { [key: string]: JsonValue };',
  'export type PgArray<T> = Array<T | null | PgArray<T>>;',
] as const;

export function documentation(
  comment: string | null,
  annotations: Annotations = {},
  schema = false,
): string {
  const lines = (comment ?? '').replaceAll('*/', '*\\/').split(/\r?\n/);
  while (lines.length && !lines[0]!.trim()) {
    lines.shift();
  }
  while (lines.length && !lines[lines.length - 1]!.trim()) {
    lines.pop();
  }

  if (schema && !lines.some((line) => /^\s*@schema(?:\s|$)/.test(line))) {
    lines.push('@schema');
  }

  for (const [key, value] of Object.entries(annotations)) {
    if (
      value === undefined ||
      lines.some((line) => new RegExp(`^\\s*@${key}(?:\\s|$)`).test(line))
    ) {
      continue;
    }
    lines.push(
      `@${key} ${typeof value === 'object' ? JSON.stringify(value) : String(value)}`.replaceAll(
        '*/',
        '*\\/',
      ),
    );
  }

  return lines.length
    ? `/**\n${lines.map((line) => (line ? ` * ${line}` : ' *')).join('\n')}\n */\n`
    : '';
}

export function propertyDeclaration(column: ResolvedColumn, expression: string): string {
  const original = column.comment ?? '';
  const comment = /^\s*@required(?:\s|$)/m.test(original)
    ? original
    : `${original}\n@required true`;

  return `${documentation(comment, column.annotations)}${JSON.stringify(column.propertyName ?? column.name)}: ${expression};`
    .split('\n')
    .map((line) => `  ${line}`)
    .join('\n');
}

export function declarationFile(sections: readonly string[], module?: string): string {
  if (module !== undefined && (!module || module.startsWith('.') || module.includes('*'))) {
    throw new Error('Expected an exact, non-relative ambient module name');
  }
  const output = sections.join('\n\n');

  return `// @generated by opentyped/odb. Do not edit.\n${
    module === undefined
      ? output
      : `declare module ${JSON.stringify(module)} {\n${output
          .split('\n')
          .map((line) => (line ? `  ${line}` : ''))
          .join('\n')}\n}`
  }\n`;
}

/** Schema modules own their names; cross-schema identifiers reference their source module. */
export function declarationModules(database: ResolvedDatabase, prefix: string): string[] {
  const schemas = [
    ...new Set([
      ...database.relations.map((relation) => relation.schema),
      ...database.identifiers.map((identifier) => identifier.schema),
      ...database.definitions.map((definition) => definition.schema),
      ...database.routines.map((routine) => routine.schema),
    ]),
  ].sort();

  return [prefix, ...schemas.map((schema) => `${prefix}/${encodeURIComponent(schema)}`)];
}

export function schemaDeclarations(
  database: ResolvedDatabase,
  prefix: string,
  render: (database: ResolvedDatabase) => readonly string[],
  tableSuffix = '',
): string {
  if (
    !prefix ||
    /[\s\\#?*]/.test(prefix) ||
    prefix.split('/').some((part) => !part || part === '.' || part === '..')
  ) {
    throw new Error('Expected a non-relative ambient module prefix');
  }
  const moduleName = (schema: string): string => `${prefix}/${encodeURIComponent(schema)}`;
  const files: string[] = [];

  for (const module of declarationModules(database, prefix).slice(1)) {
    const schema = decodeURIComponent(module.slice(prefix.length + 1));
    const scoped: ResolvedDatabase = {
      ...database,
      routines: database.routines.filter((routine) => routine.schema === schema),
      definitions: database.definitions.filter((definition) => definition.schema === schema),
      identifiers: database.identifiers.filter((identifier) => identifier.schema === schema),
      relations: database.relations
        .filter((relation) => relation.schema === schema)
        .map((relation) => ({
          ...relation,
          key: relation.name,
          columns: relation.columns.map((column) => {
            if (!column.identifiers?.length) {
              return column;
            }
            const references = column.identifiers.map((identity) => {
              if (typeof identity === 'string') {
                return identity;
              }

              if (identity.schema === schema) {
                return identity.name;
              }

              return `import(${JSON.stringify(moduleName(identity.schema))}).${identity.name}`;
            });
            const select = references.join(' | ') + (column.nullable ? ' | null' : '');

            return {
              ...column,
              value: {
                select,
                insert:
                  column.value.insert === 'never'
                    ? 'never'
                    : select + (column.insertOptional ? ' | undefined' : ''),
                update: column.value.update === 'never' ? 'never' : select,
              },
            };
          }),
        })),
    };
    files.push(declarationFile(render(scoped), moduleName(schema)));
  }
  files.push(
    declarationFile(
      [
        [
          'export interface Database {',
          ...database.relations.map(
            (relation) =>
              `  ${JSON.stringify(relation.key)}: import(${JSON.stringify(moduleName(relation.schema))}).${relation.typeName}${tableSuffix};`,
          ),
          '}',
        ].join('\n'),
      ],
      prefix,
    ),
  );

  return files
    .map((file, index) =>
      index ? file.replace('// @generated by opentyped/odb. Do not edit.\n', '') : file,
    )
    .join('\n');
}

/** SQL aliases describe driver values; composite companions describe explicitly parsed records. */
export function typeDeclarations(database: ResolvedDatabase): string[] {
  const output = database.definitions.flatMap((definition) => {
    const declarations = [
      `${documentation(definition.comment, definition.annotations)}export type ${definition.name} = ${definition.value.select};`,
    ];

    if (definition.fields) {
      declarations.push(
        [
          `export interface ${definition.name}Value {`,
          ...definition.fields.map((field) => propertyDeclaration(field, field.value.select)),
          '}',
        ].join('\n'),
      );
    }

    return declarations;
  });

  for (const routine of database.routines) {
    output.push(
      [
        `${documentation(routine.comment)}export interface ${routine.name}Parameters {`,
        ...(routine.parameters.length
          ? routine.parameters.map(
              (parameter) =>
                `  ${JSON.stringify(parameter.name)}${parameter.optional ? '?' : ''}: ${parameter.value};`,
            )
          : ['  [key: string]: never;']),
        '}',
      ].join('\n'),
    );
    output.push(
      routine.fields
        ? [
            `export interface ${routine.name}Result {`,
            ...routine.fields.map((field) => `  ${JSON.stringify(field.name)}: ${field.value};`),
            '}',
          ].join('\n')
        : `export type ${routine.name}Result = ${routine.result};`,
    );

    if (routine.rowFields) {
      output.push(
        [
          `export interface ${routine.name}Row {`,
          ...routine.rowFields.map((field) => `  ${JSON.stringify(field.name)}: ${field.value};`),
          '}',
        ].join('\n'),
      );
    }

    if (routine.setReturning) {
      output.push(`export type ${routine.name}Rows = ${routine.name}Result[];`);
    }
  }

  return output;
}
